#!/usr/bin/env node
// Bundles the GameDNA MCP server into one ESM file inside the Power, plus the built workbench.
// Playwright and Vite are NOT bundled: the server loads them from the game project at runtime.
import { build } from 'esbuild';
import { cpSync, existsSync, readdirSync, rmSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const out = path.join(root, 'power/server');
const entry = path.join(root, 'packages/mcp/src/bin.ts');
// First pass: find which third-party packages end up in the bundle, for the license banner.
const probe = await build({ entryPoints: [entry], bundle: true, platform: 'node', format: 'esm', target: 'node22', write: false, metafile: true, logLevel: 'silent' });
const bundled = new Set();
for (const f of Object.keys(probe.metafile.inputs)) {
  const m = f.match(/node_modules\/((@[^/]+\/)?[^/]+)/);
  if (m) bundled.add(m[1]);
}
const deps = [...bundled].sort().map((d) => {
  const pkg = JSON.parse(readFileSync(path.join(root, 'node_modules', d, 'package.json'), 'utf8'));
  return `${pkg.name}@${pkg.version} (${pkg.license})`;
});

await build({
  entryPoints: [entry],
  outfile: path.join(out, 'gamedna-mcp.mjs'),
  bundle: true,
  platform: 'node',
  target: 'node22',
  format: 'esm',
  minify: true,
  legalComments: 'eof',
  sourcemap: false,
  banner: {
    js: [
      '#!/usr/bin/env node',
      `// GameDNA MCP server v0.1.0 (MIT). Generated by scripts/build-power.mjs; do not edit.`,
      `// Bundled third-party packages: ${deps.join(', ')}. See docs/THIRD_PARTY_NOTICES.md.`,
      "import { createRequire as __gdCreateRequire } from 'node:module';",
      'const require = __gdCreateRequire(import.meta.url);',
    ].join('\n'),
  },
  logLevel: 'warning',
});

const wb = path.join(root, 'packages/workbench/dist');
const wbOut = path.join(out, 'workbench');
rmSync(wbOut, { recursive: true, force: true });
if (existsSync(path.join(wb, 'index.html'))) cpSync(wb, wbOut, { recursive: true });
else console.warn('build-power: workbench not built; run npm run build:workbench first');
// Full license texts for everything redistributed under power/server (bundle + workbench).
const licensed = [...bundled, 'react', 'react-dom', 'scheduler'].sort();
const texts = licensed.map((d) => {
  const dir = path.join(root, 'node_modules', d);
  const pkg = JSON.parse(readFileSync(path.join(dir, 'package.json'), 'utf8'));
  const file = readdirSync(dir).find((f) => /^licen[cs]e/i.test(f));
  return `${'='.repeat(72)}\n${pkg.name}@${pkg.version} (${pkg.license})\n${'='.repeat(72)}\n${file ? readFileSync(path.join(dir, file), 'utf8').trim() : 'License file not found in package; see the package repository.'}\n`;
});
writeFileSync(path.join(out, 'THIRD_PARTY_LICENSES.txt'), `Third-party code redistributed in power/server/. Generated by scripts/build-power.mjs.\n\n${texts.join('\n')}`);
console.log(`build-power: wrote ${path.relative(root, out)}/gamedna-mcp.mjs${existsSync(wbOut) ? ' and workbench/' : ''}`);
