/** Writes original sample assets for every style pack into packages/assets/samples/<pack>/ (GD-010). */
import { mkdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { STYLE_PACK_IDS, STYLE_PACKS, fileExtension, generateAsset, type AssetRequest } from '../src/index.js';
import { assetBytes, assetHash } from '../src/node.js';

const out = path.resolve(import.meta.dirname, '../samples');
const items: Array<[string, Omit<AssetRequest, 'styleId'>]> = [
  ['player', { type: 'sprite', seed: 7, params: { kind: 'player' } }],
  ['enemy', { type: 'sprite', seed: 8, params: { kind: 'enemy' } }],
  ['pickup', { type: 'sprite', seed: 9, params: { kind: 'pickup' } }],
  ['walk-sheet', { type: 'sprite', seed: 7, params: { kind: 'player', frames: 4 } }],
  ['tile-solid', { type: 'tile', seed: 10, params: { kind: 'solid' } }],
  ['tile-hazard', { type: 'tile', seed: 11, params: { kind: 'hazard' } }],
  ['background', { type: 'background', seed: 12, width: 480, height: 270, params: { layers: 4 } }],
  ['icon-key', { type: 'icon', seed: 13, params: { kind: 'key' } }],
  ['icon-heart', { type: 'icon', seed: 14, params: { kind: 'heart' } }],
  ['particles', { type: 'particles', seed: 15, params: { kind: 'impact' } }],
  ['sfx-jump', { type: 'sfx', seed: 16, params: { kind: 'jump' } }],
  ['sfx-hit', { type: 'sfx', seed: 17, params: { kind: 'hit' } }],
];
const manifest: Array<Record<string, unknown>> = [];
for (const id of STYLE_PACK_IDS) {
  mkdirSync(path.join(out, id), { recursive: true });
  for (const [name, req] of items) {
    const asset = generateAsset({ ...req, styleId: id });
    const file = `${id}/${name}.${fileExtension(asset)}`;
    writeFileSync(path.join(out, file), assetBytes(asset));
    manifest.push({ file, type: asset.type, kind: asset.kind, styleId: id, seed: asset.seed, width: asset.width, height: asset.height, generator: asset.generator, generatorVersion: asset.generatorVersion, sha256: assetHash(asset), license: asset.license });
  }
}
writeFileSync(path.join(out, 'manifest.json'), `${JSON.stringify({ note: 'Original GameDNA sample assets, regenerated by packages/assets/scripts/generate-samples.ts', assets: manifest }, null, 2)}\n`);
// Contact sheet for previews.
const cards = STYLE_PACK_IDS.map((id) => {
  const p = STYLE_PACKS[id];
  const img = (n: string, ext: string, w: number) => `<img src="${id}/${n}.${ext}" width="${w}" alt="${p.name} ${n}" style="image-rendering:${p.rendering.mode === 'raster-pixel' ? 'pixelated' : 'auto'}">`;
  const ext = p.rendering.mode === 'raster-pixel' ? 'png' : 'svg';
  const swatches = Object.entries(p.palette).map(([n, c]) => `<span title="${n}" style="display:inline-block;width:18px;height:18px;background:${c};border:1px solid #0003"></span>`).join('');
  return `<section style="background:${p.roles.background};color:${p.roles.foreground};padding:16px;border-radius:10px;font-family:${p.typography.family.replace(/"/g, "'")}"><h2 style="margin:0 0 4px;letter-spacing:${p.typography.letterSpacingPx}px;text-transform:${p.typography.transform}">${p.name}</h2><p style="margin:0 0 8px;font-size:13px">${p.summary}</p>${img('background', ext, 448)}<div style="display:flex;gap:12px;align-items:center;margin-top:10px">${img('player', ext, 64)}${img('enemy', ext, 64)}${img('pickup', ext, 64)}${img('tile-solid', ext, 64)}${img('tile-hazard', ext, 64)}${img('icon-key', 'svg', 40)}${img('icon-heart', 'svg', 40)}</div><div style="margin-top:8px">${img('walk-sheet', ext, 256)}</div><div style="margin-top:8px">${swatches}</div><p style="font-size:12px;margin:8px 0 0">camera ${p.camera.follow} · motion ${p.motion.easing} @ ${p.motion.animationFps} fps · feedback ${p.feedback.particleShape}/${p.feedback.flash}</p></section>`;
}).join('');
writeFileSync(path.join(out, 'index.html'), `<!doctype html><html lang="en"><meta charset="utf-8"><title>GameDNA style packs</title><body style="margin:0;padding:16px;background:#f3efe8;display:grid;grid-template-columns:repeat(3,480px);gap:16px">${cards}</body></html>\n`);
console.log(`wrote ${manifest.length} sample assets to ${path.relative(process.cwd(), out)}`);
